    private void formComponentShown(java.awt.event.ComponentEvent evt) {//GEN-FIRST:event_formComponentShown
        ArrayList<Workout> list = WorkoutDao.getAllRecords();
        Iterator<Workout> itr = list.iterator();
        while (itr.hasNext()) {
            Workout workoutObj = itr.next();
            txtCategory.addItem(workoutObj.getname());
        }

        // TODO add your handling code here:
    }//GEN-LAST:event_formComponentShown

    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        Exercise addexercise = new Exercise();
        addexercise.setName(txtName.getText());
        addexercise.setCategory((String) txtCategory.getSelectedItem());
        addexercise.setSetsReps(txtSetsReps.getText());
        Exercisedao.SAVE(addexercise);
        setVisible(false);
        new AddNewExercise().setVisible(true);
// TODO add your handling code here:
    }//GEN-LAST:event_btnSaveActionPerformed

