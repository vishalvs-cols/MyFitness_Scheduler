    public void getAllRecords(String email){
        DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
        dtm.setRowCount(0);
        ArrayList<User> list = userdao.getAllRecords(email);
        Iterator<User> itr = list.iterator();
        while(itr.hasNext()){
            User userObj = itr.next();
            if(!userObj.getEmail().equals("vishal2405.mcmt@gmail.com")){
                dtm.addRow(new Object[]{userObj.getUser_id(), userObj.getName(), userObj.getEmail(), userObj.getPassword(), userObj.getAge(), userObj.getGender()});
                
            }
        }
        
    }

