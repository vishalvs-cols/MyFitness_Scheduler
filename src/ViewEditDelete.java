    private void formComponentShown(java.awt.event.ComponentEvent evt) {//GEN-FIRST:event_formComponentShown
    DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
    ArrayList<Exercise> list = Exercisedao.getAllRecords();
    Iterator<Exercise> itr = list.iterator();
    while(itr.hasNext()){
        Exercise addexerciseObj  = itr.next();
        dtm.addRow(new Object[]{addexerciseObj.getId(), addexerciseObj.getName(), addexerciseObj.getCategory(), addexerciseObj.getSetsReps()});
        
    }
            // TODO add your handling code here:
    }//GEN-LAST:event_formComponentShown

    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        int index = jTable1.getSelectedRow();
        TableModel model = jTable1.getModel();
        String id = model.getValueAt(index,0).toString();
        lblId.setText(id);
        String name = model.getValueAt(index,1).toString();
        txtName.setText(name);
        String category = model.getValueAt(index,2).toString();
        String setsreps = model.getValueAt(index, 3).toString();
        txtSetsReps.setText(setsreps);

        btnUpdate.setEnabled(true);
        btnDelete.setEnabled(true);
        txtCategory.removeAllItems();
        txtCategory.addItem(category);
        ArrayList<Workout>  workoutlist = WorkoutDao.getAllRecords();
        Iterator<Workout> workoutitr = workoutlist.iterator();
        while(workoutitr.hasNext()){
            Workout  exercisecategoryObj = workoutitr.next();
            if(!exercisecategoryObj.getname().equals(category)){
               txtCategory.addItem(exercisecategoryObj.getname());
            }
        }// TODO add your handling code here:
    }//GEN-LAST:event_jTable1MouseClicked

