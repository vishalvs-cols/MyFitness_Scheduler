    private void loadDates() {
        cmbDate.removeAllItems();
        cmbDate.addItem("All Dates");
        for (String d : ScheduleDao.getDates(userEmail)) {
            cmbDate.addItem(d);
        }
    }

    private void loadTable(String date) {
        DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
        dtm.setRowCount(0);
        for (Object[] row : ScheduleDao.getWorkouts(userEmail, date)) {
            dtm.addRow(row);
        }
        lblInfo.setText(dtm.getRowCount() == 0
                ? "No Exercise are added here !"
                : dtm.getRowCount() + "exercise");
    }

